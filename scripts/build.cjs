const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourceFiles = [
  'config.js',
  'state.js',
  'ui.js',
  'session.js',
  'encounters.js',
  'weapons.js',
  'progression.js',
  'damage.js',
  'abilities.js',
  'simulation.js',
  'renderer.js',
  'input.js'
];
const banner = '// Generated by scripts/build.cjs from src/. Edit the source files, then run node scripts/build.cjs.\n';
const output = banner + sourceFiles.map(file => fs.readFileSync(path.join(root, 'src', file), 'utf8').trimEnd()).join('\n\n') + '\n';
const bundlePath = path.join(root, 'dist', 'game.js');

if (process.argv.includes('--check')) {
  if (!fs.existsSync(bundlePath) || fs.readFileSync(bundlePath, 'utf8') !== output) {
    console.error('dist/game.js is out of date. Run node scripts/build.cjs.');
    process.exitCode = 1;
  } else {
    console.log('dist/game.js matches src/.');
  }
} else {
  fs.mkdirSync(path.dirname(bundlePath), {recursive:true});
  fs.writeFileSync(bundlePath, output);
  console.log(`Built dist/game.js from ${sourceFiles.length} source files.`);
}
